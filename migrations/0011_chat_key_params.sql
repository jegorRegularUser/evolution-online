-- едут ключ словаря и параметры подстановки. Клиент при lang=en собирает текст
-- по ключу, а старые строки без key показывают исходный русский текст — тот же
-- контракт, что у журнала движка (key выигрывает, ru — фолбэк).
alter table evo_chat add column if not exists "key" text;
