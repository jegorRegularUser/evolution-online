-- Косметика места (волна «аватары и рубашки»).
-- avatar: ключ аватара места — «sci.<имя учёного>» (бесплатный набор) или
--   item_id каталога «avatar.*» (существа за ископаемые). Публичная
--   информация: видна всем за столом, маскировать не нужно. Пусто —
--   детерминированный дефолт по имени (у ботов — портрет их учёного).
-- cardback: item_id каталога «cardback.*» — рубашка карт владельца места.
--   Пусто — классика слота. Оба поля проверяются сервисом на владение
--   платных предметов; в БД — свободный текст без FK на каталог.
alter table evo_seats add column if not exists avatar text;
alter table evo_seats add column if not exists cardback text;
