/** Максимум красных фишек на одной карте флоры (золотое правило дополнения). */
export const FLORA_MAX_TOKENS = 4;

/** Максимум карт флоры на столе (официальное правило). */
export const FLORA_TABLE_MAX = 8;

/** Меток каждого вида в комплекте. */
export const MARKS_PER_KIND = 4;

/** Колода флоры: 12 уникальных карт × 2 копии = 24. */
export function floraDeckKinds(): FloraKind[] {
  return (Object.keys(FLORA) as FloraKind[]).flatMap((k) => [k, k]);
}

export function floraDeckSize(): number {
  return floraDeckKinds().length;
}

/** Полный стол меток в начале партии: по 4 каждого вида. */
export function fullMarksPool(): Record<MarkKind, number> {
  const pool = {} as Record<MarkKind, number>;
  for (const id of Object.keys(MARKS) as MarkKind[]) pool[id] = MARKS_PER_KIND;
  return pool;
}
